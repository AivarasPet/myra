#!/usr/bin/env bash
# Downloads lucide-static and generates ios/Sverto/Resources/Lucide.xcassets (template SVG imagesets)
# plus ios/Sverto/Generated/LucideIconNames.swift. Both outputs are gitignored, like Android's icon dependency.
set -euo pipefail
LUCIDE_VERSION="${LUCIDE_VERSION:-1.41.0}"
REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
ASSETS="$REPO_ROOT/ios/Sverto/Resources/Lucide.xcassets"
NAMES_SWIFT="$REPO_ROOT/ios/Sverto/Generated/LucideIconNames.swift"
CACHE="$REPO_ROOT/server/target/lucide-static-$LUCIDE_VERSION"

if [ -f "$ASSETS/.version" ] && [ "$(cat "$ASSETS/.version")" = "$LUCIDE_VERSION" ] && [ -f "$NAMES_SWIFT" ] && [ "${FORCE:-0}" != "1" ]; then
  echo "Lucide.xcassets $LUCIDE_VERSION is up to date"
  exit 0
fi

if [ ! -d "$CACHE/package/icons" ]; then
  mkdir -p "$CACHE"
  echo "Downloading lucide-static $LUCIDE_VERSION"
  curl -fsSL "https://registry.npmjs.org/lucide-static/-/lucide-static-$LUCIDE_VERSION.tgz" | tar -xz -C "$CACHE"
fi

rm -rf "$ASSETS"
mkdir -p "$ASSETS" "$(dirname "$NAMES_SWIFT")"
cat > "$ASSETS/Contents.json" <<'JSON'
{
  "info" : { "author" : "xcode", "version" : 1 }
}
JSON

names=()
for svg in "$CACHE"/package/icons/*.svg; do
  name="$(basename "$svg" .svg)"
  set_dir="$ASSETS/lucide-$name.imageset"
  mkdir -p "$set_dir"
  cp "$svg" "$set_dir/$name.svg"
  cat > "$set_dir/Contents.json" <<JSON
{
  "images" : [ { "filename" : "$name.svg", "idiom" : "universal" } ],
  "info" : { "author" : "xcode", "version" : 1 },
  "properties" : { "preserves-vector-representation" : true, "template-rendering-intent" : "template" }
}
JSON
  names+=("$name")
done

{
  echo "// Generated by ios/scripts/make-lucide-assets.sh (lucide-static $LUCIDE_VERSION). Do not edit."
  echo "enum LucideIconNames {"
  echo "    static let all: [String] = ["
  for n in "${names[@]}"; do echo "        \"$n\","; done
  echo "    ]"
  echo "}"
} > "$NAMES_SWIFT"
echo "$LUCIDE_VERSION" > "$ASSETS/.version"
echo "Generated ${#names[@]} Lucide imagesets"
