#!/usr/bin/env bash
# Writes ios/Config/Generated.xcconfig from the repo .env (dev) or from explicit environment overrides.
# Recognised overrides: APP_API_BASE_URL, CLERK_PUBLISHABLE_KEY, IOS_TEAM_ID.
set -euo pipefail
REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
OUT="$REPO_ROOT/ios/Config/Generated.xcconfig"

env_value() {
  local key="$1"
  [ -f "$REPO_ROOT/.env" ] || return 0
  sed -n "s/^${key}=//p" "$REPO_ROOT/.env" | tail -n1
}

SERVER_PORT="$(env_value SERVER_PORT)"
API_BASE_URL="${APP_API_BASE_URL:-$(env_value APP_API_BASE_URL)}"
API_BASE_URL="${API_BASE_URL:-http://localhost:${SERVER_PORT:-7002}}"
CLERK_KEY="${CLERK_PUBLISHABLE_KEY:-$(env_value CLERK_PUBLISHABLE_KEY)}"
TEAM_ID="${IOS_TEAM_ID:-$(env_value IOS_TEAM_ID)}"

# xcconfig treats "//" as a comment, so the URL scheme separator is written as "/$()/".
SCHEME_SEP='/$()/'
XC_URL="${API_BASE_URL//\/\//$SCHEME_SEP}"

{
  echo "// Generated by ios/scripts/write-generated-xcconfig.sh — do not edit, do not commit"
  echo "API_BASE_URL = $XC_URL"
  echo "CLERK_PUBLISHABLE_KEY = $CLERK_KEY"
  echo "DEVELOPMENT_TEAM = $TEAM_ID"
} > "$OUT"
echo "Wrote $OUT (API_BASE_URL=$API_BASE_URL, clerk=$([ -n "$CLERK_KEY" ] && echo set || echo empty), team=${TEAM_ID:-none})"
