#!/usr/bin/env bash
# Builds the Rust core for iOS, generates the UniFFI Swift bindings and packages SvertoCoreFFI.xcframework.
# Usage: build-core.sh [sim|all]   (sim = simulator slice only, all = simulator + device)
# Env:   FORCE=1 rebuilds even when the xcframework is newer than every Rust input.
set -euo pipefail

VARIANT="${1:-sim}"
REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
SERVER_DIR="$REPO_ROOT/server"
IOS_DIR="$REPO_ROOT/ios"
PACKAGE_DIR="$IOS_DIR/SvertoCore"
XCFRAMEWORK="$PACKAGE_DIR/Frameworks/SvertoCoreFFI.xcframework"
SWIFT_OUT="$PACKAGE_DIR/Sources/SvertoCore"
STAGING="$SERVER_DIR/target/ios-bindings"
CARGO="${CARGO_HOME:-$HOME/.cargo}/bin/cargo"
export IPHONEOS_DEPLOYMENT_TARGET="${IPHONEOS_DEPLOYMENT_TARGET:-26.0}"
export PATH="$PATH:/usr/bin:/bin:/usr/sbin:/sbin"

SIM_TARGET="aarch64-apple-ios-sim"
DEVICE_TARGET="aarch64-apple-ios"
SIM_LIB="$SERVER_DIR/target/$SIM_TARGET/release/libsverto_core.a"
DEVICE_LIB="$SERVER_DIR/target/$DEVICE_TARGET/release/libsverto_core.a"

case "$VARIANT" in
  sim|all) ;;
  *) echo "usage: $0 [sim|all]" >&2; exit 2 ;;
esac

inputs=(
  "$SERVER_DIR/app-core/src"
  "$SERVER_DIR/app-core/Cargo.toml"
  "$SERVER_DIR/app-core/uniffi.toml"
  "$SERVER_DIR/shared/src"
  "$SERVER_DIR/shared/uniffi.toml"
  "$SERVER_DIR/vendor/uniffi_core/src"
  "$SERVER_DIR/Cargo.toml"
  "$SERVER_DIR/Cargo.lock"
  "$IOS_DIR/scripts/build-core.sh"
)

is_up_to_date() {
  [ "${FORCE:-0}" = "1" ] && return 1
  [ -f "$XCFRAMEWORK/Info.plist" ] || return 1
  [ -f "$SWIFT_OUT/sverto_core.swift" ] || return 1
  if [ "$VARIANT" = "all" ]; then
    [ -d "$XCFRAMEWORK/ios-arm64" ] || return 1
  fi
  local newest
  newest="$(find "${inputs[@]}" -type f -newer "$XCFRAMEWORK/Info.plist" -print -quit 2>/dev/null || true)"
  [ -z "$newest" ]
}

if is_up_to_date; then
  echo "SvertoCoreFFI.xcframework is up to date"
  exit 0
fi

echo "Building sverto-core for $SIM_TARGET"
(cd "$SERVER_DIR" && "$CARGO" build --release -p sverto-core --target "$SIM_TARGET")
if [ "$VARIANT" = "all" ]; then
  echo "Building sverto-core for $DEVICE_TARGET"
  (cd "$SERVER_DIR" && "$CARGO" build --release -p sverto-core --target "$DEVICE_TARGET")
fi

echo "Generating Swift bindings"
rm -rf "$STAGING"
mkdir -p "$STAGING/Headers" "$SWIFT_OUT"
(cd "$SERVER_DIR" && "$CARGO" run --release -p sverto-core --bin uniffi-bindgen-swift -- \
  --swift-sources --headers --modulemap \
  --module-name SvertoCoreFFI --modulemap-filename module.modulemap \
  --link-frameworks Security --link-frameworks CoreFoundation \
  "$SIM_LIB" "$STAGING")
mv "$STAGING"/*.h "$STAGING"/module.modulemap "$STAGING/Headers/"
find "$SWIFT_OUT" -name '*.swift' -delete
mv "$STAGING"/*.swift "$SWIFT_OUT/"
{
  echo "// Generated by ios/scripts/build-core.sh: UniFFI records and enums are plain values, safe to send across actors."
  echo "import Foundation"
  grep -hoE '^public (struct|enum) [A-Za-z0-9_]+' "$SWIFT_OUT"/*.swift | awk '{print "extension " $3 ": @unchecked Sendable {}"}' | sort -u
} > "$SWIFT_OUT/Sendable+Generated.swift"

echo "Packaging $XCFRAMEWORK"
rm -rf "$XCFRAMEWORK"
args=(-library "$SIM_LIB" -headers "$STAGING/Headers")
if [ "$VARIANT" = "all" ]; then
  args+=(-library "$DEVICE_LIB" -headers "$STAGING/Headers")
fi
xcodebuild -create-xcframework "${args[@]}" -output "$XCFRAMEWORK" >/dev/null
touch "$XCFRAMEWORK/Info.plist"
echo "Done: $XCFRAMEWORK ($VARIANT)"
